import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const normalizeLineEndings = (value) => value.replace(/\r\n?/g, '\n');
const linkage = normalizeLineEndings(await readFile(new URL('../public/material-linkage.js', import.meta.url), 'utf8'));
const importer = normalizeLineEndings(await readFile(new URL('../public/material-import.js', import.meta.url), 'utf8'));
const projectImporter = normalizeLineEndings(await readFile(new URL('../public/project-import.js', import.meta.url), 'utf8'));
const linkedSource = linkage.replace(/^export\s+/gm, '');
const parserSource = importer
  .replace(/^import\s+\{[^}]+\}\s+from\s+['"]\.\/material-linkage\.js['"];\s*/m, '')
  .replace(/^export\s+/gm, '');

if (parserSource === importer) throw new Error('Could not remove material-import.js module import.');
const projectParserSource = projectImporter
  .replace(/^export\s+/gm, '')
  .replace(/\bnormalizeValue\b/g, 'normalizeQldaValue');

const bundle = [
  '/* Generated by scripts/build-drive-sync-parser.js; do not edit directly. */',
  'function createAmeccDriveParser(XLSX) {',
  linkedSource,
  parserSource,
  projectParserSource,
  'return { projectCodeFromFilename, parseMaterialWorkbook, parseProjectWorkbook };',
  '}',
  '',
].join('\n');

await writeFile(new URL('../public/drive-sync-parser.js', import.meta.url), bundle);

const xlsx = await readFile(new URL('../public/vendor/xlsx.full.min.js', import.meta.url), 'utf8');
const sha256 = (value) => createHash('sha256').update(value, 'utf8').digest('hex');
const codeUrl = new URL('../drive-sync/Code.gs', import.meta.url);
let code = await readFile(codeUrl, 'utf8');
code = code.replace(/const AMECC_PARSER_SHA256 = '[^']*';/, `const AMECC_PARSER_SHA256 = '${sha256(bundle)}';`);
code = code.replace(/const AMECC_XLSX_SHA256 = '[^']*';/, `const AMECC_XLSX_SHA256 = '${sha256(xlsx)}';`);
if (code.includes('__PARSER_SHA256__') || code.includes('__XLSX_SHA256__')) {
  throw new Error('Could not replace Apps Script parser integrity placeholders.');
}
await writeFile(codeUrl, code);
